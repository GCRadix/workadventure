#!/usr/bin/env python3
"""
Packs every individual object PNG in maps/assets/objects/ (except objects_XX.png sheets)
into one 32px-grid tileset image: maps/assets/objects_combined.png

Positions are STABLE: objects already listed in objects_combined.manifest.json keep their
spot, so tiles already placed in maps never shift. New objects fill free space; the sheet
only ever grows downwards (never wider), which is safe for existing maps.

Usage (from the repo root or anywhere):
    python maps/references/build_objects_sheet.py
Requires: Pillow  (pip install pillow)
"""
import json
import re
import sys
from pathlib import Path

from PIL import Image

TILE = 32
COLUMNS = 24  # sheet width in tiles. Never change this once maps use the sheet.

ROOT = Path(__file__).resolve().parent.parent  # maps/
SRC = ROOT / "assets" / "objects"
OUT_PNG = ROOT / "assets" / "objects_combined.png"
OUT_MANIFEST = ROOT / "assets" / "objects_combined.manifest.json"
SKIP = re.compile(r"^objects_\d+\.png$", re.I)


def main() -> int:
    files = sorted((p for p in SRC.glob("*.png") if not SKIP.match(p.name)), key=lambda p: p.name.lower())
    old = {}
    if OUT_MANIFEST.exists():
        m = json.loads(OUT_MANIFEST.read_text(encoding="utf-8"))
        if m.get("columns") != COLUMNS:
            print("Manifest was built with a different width; refusing to repack.", file=sys.stderr)
            return 1
        old = m["objects"]

    images, problems = {}, []
    for p in files:
        im = Image.open(p).convert("RGBA")
        if im.width % TILE or im.height % TILE:
            problems.append(f"{p.name}: {im.width}x{im.height} is not a multiple of {TILE}px (skipped)")
            continue
        if im.width // TILE > COLUMNS:
            problems.append(f"{p.name}: wider than the sheet (skipped)")
            continue
        images[p.stem] = im

    grid = []  # rows of booleans

    def ensure_rows(n):
        while len(grid) < n:
            grid.append([False] * COLUMNS)

    def free(x, y, w, h):
        ensure_rows(y + h)
        return all(not grid[r][c] for r in range(y, y + h) for c in range(x, x + w))

    def take(x, y, w, h):
        ensure_rows(y + h)
        for r in range(y, y + h):
            for c in range(x, x + w):
                grid[r][c] = True

    placed = {}
    # 1) keep known objects where they were (if their size is unchanged)
    for name, im in images.items():
        o = old.get(name)
        w, h = im.width // TILE, im.height // TILE
        if o and o["w"] == w and o["h"] == h and free(o["x"], o["y"], w, h):
            take(o["x"], o["y"], w, h)
            placed[name] = (o["x"], o["y"], w, h)
    # 2) first-fit for new / resized objects, in alphabetical order
    for name, im in images.items():
        if name in placed:
            continue
        w, h = im.width // TILE, im.height // TILE
        y = 0
        while True:
            spot = next((x for x in range(COLUMNS - w + 1) if free(x, y, w, h)), None)
            if spot is not None:
                take(spot, y, w, h)
                placed[name] = (spot, y, w, h)
                break
            y += 1

    removed = sorted(set(old) - set(placed))
    rows = max((y + h for (_, y, _, h) in placed.values()), default=1)
    if OUT_PNG.exists():  # never shrink: keeps tile ids of later rows valid
        rows = max(rows, Image.open(OUT_PNG).height // TILE)
    sheet = Image.new("RGBA", (COLUMNS * TILE, rows * TILE), (0, 0, 0, 0))
    for name, (x, y, w, h) in placed.items():
        sheet.paste(images[name], (x * TILE, y * TILE))
    sheet.save(OUT_PNG, optimize=True)

    manifest = {
        "columns": COLUMNS,
        "tile": TILE,
        "image": OUT_PNG.name,
        "note": "Generated by maps/references/build_objects_sheet.py. x/y/w/h are in tiles; "
                "localTileId is the tile index of the object's top-left corner inside the tileset.",
        "objects": {
            n: {"file": f"objects/{n}.png", "x": x, "y": y, "w": w, "h": h, "localTileId": y * COLUMNS + x}
            for n, (x, y, w, h) in sorted(placed.items(), key=lambda kv: (kv[1][1], kv[1][0]))
        },
    }
    OUT_MANIFEST.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")

    print(f"{len(placed)} objects -> {OUT_PNG.name} ({sheet.width}x{sheet.height}, {COLUMNS}x{rows} tiles)")
    for p in problems:
        print("  !", p)
    if removed:
        print("  ! no longer in objects/ (their tiles are now empty):", ", ".join(removed))
    return 0


if __name__ == "__main__":
    sys.exit(main())
